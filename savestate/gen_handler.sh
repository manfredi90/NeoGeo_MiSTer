#!/bin/sh
# Assemble the 68000 savestate handler and write it as a ROM table for rtl/ss/ss_ctrl.sv.
# Needs binutils for m68k (Debian/Ubuntu: binutils-m68k-linux-gnu).
set -e
cd "$(dirname "$0")"
m68k-linux-gnu-as -m68000 -o /tmp/ss_handler.o handler.s
m68k-linux-gnu-objcopy -O binary /tmp/ss_handler.o /tmp/ss_handler.bin
python3 - /tmp/ss_handler.bin ../rtl/ss/ss_handler.vh <<'PY'
import sys
d = open(sys.argv[1], 'rb').read()
w = [d[i] << 8 | d[i + 1] for i in range(0, len(d), 2)]
assert len(w) <= 64
with open(sys.argv[2], 'w') as f:
    f.write("// Generated by savestate/gen_handler.sh from savestate/handler.s\n")
    f.write("always @(*) begin\n\tcase (rom_addr)\n")
    for i, v in enumerate(w):
        f.write("\t\t6'd%d: rom_q = 16'h%04X;\n" % (i, v))
    f.write("\t\tdefault: rom_q = 16'h4E71; // nop\n\tendcase\nend\n")
PY
rm -f /tmp/ss_handler.o /tmp/ss_handler.bin
